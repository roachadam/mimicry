// report is everything a run measured.
type report struct {
	Date string `json:"date"`
	// Name is the report's file name before the date ("bench" when empty).
	Name     string       `json:"name,omitempty"`
	Env      env          `json:"env"`
	Settings settings     `json:"settings"`
	Micro    string       `json:"micro,omitempty"`
	MicroRaw string       `json:"microRaw,omitempty"`
	Load     []loadPoint  `json:"load,omitempty"`
	Idle     []idlePoint  `json:"idle,omitempty"`
	Pages    []pagePoint  `json:"pages,omitempty"`
	Multi    []multiPoint `json:"multi,omitempty"`
}

// mimicryH1Limit is Chrome's HTTP/1.1 connections per host, which mimicry
// keeps (profile connections.http1PerHost).
const mimicryH1Limit = 6

func (r *report) markdown() string {
	var b strings.Builder

	w := func(format string, args ...any) {
		fmt.Fprintf(&b, format, args...)
	}

	name := r.Name
	if name == "" {
		name = "bench"
	}

	w("# mimicry benchmark, %s\n\n", r.Date)
	w("Generated by `internal/bench/cmd/bench` (`moon run bench:run`); the raw numbers are in `%s-%s.json`. ", name, r.Date)
	w("How to run it, locally or against a remote server: [`internal/bench/README.md`](../README.md).\n\n")

	r.summary(w)
	r.environment(w)
	r.fairness(w)
	r.micro(w)
	r.loadTables(w)
	r.idleTable(w)
	r.pageTables(w)
	r.multiTables(w)
	r.skipped(w)

	return b.String()
}

type writer func(format string, args ...any)

func (r *report) clientNames() []string {
	out := make([]string, 0, len(r.Env.Clients))

	for _, c := range r.Env.Clients {
		if slices.Contains(r.Settings.Clients, c.Name) {
			out = append(out, c.Name)
		}
	}

	return out
}

// summary compares mimicry with each other client over the load points
// both completed: the geometric mean of mimicry's value over the other's.
func (r *report) summary(w writer) {
	if len(r.Load) == 0 {
		return
	}

	w("## Summary: mimicry against the others (layer 3)\n\n")
	w("Geometric mean, over every load point (server, protocol, body, concurrency) both clients completed, ")
	w("of mimicry's value divided by the other client's. Below 1.00 means mimicry is lower: better for latency, CPU and ")
	w("allocations, worse for requests per second. HTTP/1.1 points above %d concurrent requests are left out (mimicry queues ", mimicryH1Limit)
	w("there by design, see the fairness notes); they are in the tables.\n\n")

	others := slices.DeleteFunc(r.clientNames(), func(s string) bool {
		return s == "mimicry"
	})

	metrics := []struct {
		name string
		get  func(*scenario.LoadResult) float64
	}{
		{"requests/s", func(l *scenario.LoadResult) float64 { return l.RPS }},
		{"p50 latency", func(l *scenario.LoadResult) float64 { return l.P50 }},
		{"p99 latency", func(l *scenario.LoadResult) float64 { return l.P99 }},
		{"client CPU per request", func(l *scenario.LoadResult) float64 { return l.CPUPerRequest }},
		{"bytes allocated per request", func(l *scenario.LoadResult) float64 { return l.BytesPerRequest }},
		{"allocations per request", func(l *scenario.LoadResult) float64 { return l.AllocsPerRequest }},
		{"peak heap", func(l *scenario.LoadResult) float64 { return l.HeapPeakMB }},
	}

	for _, p := range target.Protos {
		w("**%s**\n\n| metric | %s |\n|---|%s\n", p.Wire(), strings.Join(prefixAll("vs ", others), " | "), strings.Repeat("---|", len(others)))

		for _, m := range metrics {
			w("| %s |", m.name)

			for _, o := range others {
				g, n := r.ratio(p, o, m.get)
				if n == 0 {
					w(" n/a |")

					continue
				}

				w(" %.2f× (%d) |", g, n)
			}

			w("\n")
		}

		w("\n")
	}

	w("The number in brackets is how many load points the mean is over.\n\n")
}

func prefixAll(prefix string, s []string) []string {
	out := make([]string, len(s))
	for i, v := range s {
		out[i] = prefix + v
	}

	return out
}

// ratio returns the geometric mean of mimicry's metric over other's on p.
func (r *report) ratio(p target.Proto, other string, get func(*scenario.LoadResult) float64) (float64, int) {
	type key struct {
		server, op string
		conc       int
	}

	mine := map[key]*scenario.LoadResult{}
	theirs := map[key]*scenario.LoadResult{}

	for _, lp := range r.Load {
		if lp.Proto != p || !lp.valid() {
			continue
		}

		if p == target.H1 && lp.Conc > mimicryH1Limit {
			continue
		}

		k := key{
			server: lp.Server,
			op:     lp.Op,
			conc:   lp.Conc,
		}

		switch lp.Client {
		case "mimicry":
			mine[k] = lp.Result
		case other:
			theirs[k] = lp.Result
		}
	}

	var (
		sum float64
		n   int
	)

	for k, m := range mine {
		t, ok := theirs[k]
		if !ok {
			continue
		}

		a, b := get(m), get(t)
		if a <= 0 || b <= 0 {
			continue
		}

		sum += math.Log(a / b)
		n++
	}

	if n == 0 {
		return 0, 0
	}

	return math.Exp(sum / float64(n)), n
}

func (lp loadPoint) valid() bool {
	return lp.NA == "" && lp.Error == "" && lp.Result != nil && lp.Result.Discarded == ""
}

func (r *report) environment(w writer) {
	e := r.Env
	st := r.Settings

	w("## Environment\n\n")
	w("| | |\n|---|---|\n")
	w("| Host | %s, %s, %s |\n", e.Host, e.HostCPU, e.HostOS)
	w("| Docker | %s; Linux %s |\n", e.Docker, e.Kernel)
	w("| Mode | %s |\n", e.Mode)
	w("| CPU sets | %s; the client sees %d CPUs, GOMAXPROCS %d |\n", e.Cpusets, e.ClientCPUs, e.GOMAXPROCS)
	w("| Go | %s (clients and the Go server) |\n", e.GoVersion)
	w("| mimicry | %s |\n", e.MimicryCommit)

	for _, s := range e.Servers {
		w("| Server %s | %s, %d CPUs |\n", s.Name, s.Software, s.CPUs)
	}

	ran := func(layer int) bool {
		return slices.Contains(st.Layers, layer)
	}

	if ran(5) {
		w("| netem (layer 5) | %s |\n", e.Netem)
	}

	w("| Proxy delay | %s |\n", e.ProxyDelay)

	if ran(3) {
		w("| Load points | warm-up %v, then %v measured |\n", st.Warmup, st.Window)
		w("| Concurrency | %v (reduced matrix on %s: 1 and 64, bodies 1KB and 100KB) |\n", st.Concurrency, strings.Join(st.Reduced, ", "))
	}

	if ran(4) {
		w("| Idle memory | %d clients per measurement, on %s |\n", st.IdleN, firstOr(st.Servers, "?"))
	}

	if ran(5) {
		w("| Page loads | %d per setup and condition, each on a new client (cold) and again on the same client (warm), Go server |\n", st.Reps)
	}

	if ran(6) {
		variants := st.MultiVariants
		if len(variants) == 0 {
			// Reports from before -multi-variants ran these two.
			variants = []string{variantFixed, variantProxy}
		}

		w("| Many clients (layer 6) | %d clients (routines) per point in one process, each through a proxy identity of its own, ", st.MultiN)
		w("one request at a time; warm-up %v; variants %s", st.Warmup, strings.Join(variants, ", "))

		if slices.Contains(variants, variantFixed) || slices.Contains(variants, variantProxy) {
			w("; %v measured", st.Window)
		}

		if slices.Contains(variants, variantProxy) {
			w("; proxy rotation: a new identity every %d requests", st.MultiRotate)
		}

		if slices.Contains(variants, variantClient) {
			w("; client rotation: a new client every %d requests, %v measured", st.MultiRotate, st.MultiClientWindow)
		}

		w(" |\n")
	}

	w("\n")

	w("| Client | Module | Version | Profile |\n|---|---|---|---|\n")

	for _, c := range e.Clients {
		w("| %s | `%s` | %s | %s |\n", c.Name, c.Module, c.Version, c.Profile)
	}

	w("\n")
}

func firstOr(s []string, def string) string {
	if len(s) == 0 {
		return def
	}

	return s[0]
}

func (r *report) fairness(w writer) {
	w("## Fairness notes\n\n")

	notes := []string{
		"**Protocol checks.** Every measured response is checked against the protocol under test using the server's own view " +
			"(its `x-proto` header: `$server_protocol` in nginx, `r.Proto` in the Go server). A load point with a single response on " +
			"another protocol is discarded with the reason, as is a micro benchmark (it prints no result). Before measuring, each " +
			"client is warmed up until three responses in a row come over the protocol.",
		"**How each protocol is reached.** HTTP/1.1 is tested on each server's http/1.1-only port (ALPN offers nothing else, no " +
			"Alt-Svc) for every client, plus the client's own switch where it has one (tls-client `WithForceHttp1`, httpcloak " +
			"`WithForceHTTP1`, azuretls `ForceHTTP1`, net/http `Protocols`). HTTP/2: mimicry `Config.DisableHTTP3`, httpcloak " +
			"`WithForceHTTP2`, tls-client `WithDisableHttp3`, net/http `Protocols`, azuretls ALPN with HTTP/3 never enabled. " +
			"HTTP/3: net/http's baseline is quic-go's `http3.Transport`; httpcloak `WithForceHTTP3`; azuretls `EnableHTTP3` + " +
			"`ForceHTTP3`; tls-client has no HTTP/3-only switch, so `WithProtocolRacing` (QUIC against TCP per host, winner kept); " +
			"**mimicry has no switch either: it moves to HTTP/3 after the server's Alt-Svc, as Chrome does**, so it is warmed up " +
			"onto HTTP/3 and a fresh Transport can never start on it (layer 2 `handshake=full` over HTTP/3 is n/a for mimicry).",
		"**Certificates.** Every client verifies the servers against the benchmark's CA; no client skips verification in any " +
			"scenario. azuretls's HTTP/3 transport ignores its TLS configuration hook, so it trusts the CA through the system roots " +
			"(`SSL_CERT_FILE` points at the CA in the client container); the others get it as a pool.",
		"**Bodies.** Each client is used through its ordinary request API: net/http, mimicry and tls-client stream the body " +
			"(drained into `io.Discard`); httpcloak's `Session.Do` and azuretls's `Session.Do` return it fully buffered, so their " +
			"allocations grow with the body (10 MB per request at the largest size).",
		"**Headers.** mimicry sends its Chrome profile's headers for the request's kind: the micro and load scenarios' requests " +
			"are `Fetch` calls from a page on the same origin (no CORS preflight), page loads are a navigation and element kinds. " +
			"httpcloak sends its preset's headers. tls-client and azuretls get a fixed set of Chrome's navigation headers, in " +
			"Chrome's order, as their users pass them. net/http sends Go's few default headers. Request sizes therefore differ by a " +
			"few hundred bytes; HPACK/QPACK make that small on a warm connection.",
		"**Profiles.** Each client's newest Chrome: mimicry `chrome-156-macos`, httpcloak `chrome-latest` (155), tls-client " +
			"`Chrome_152_PSK` (the variant of 152 that resumes TLS sessions as Chrome does; plain `Chrome_152` keeps no session " +
			"cache), azuretls `chrome` (its spec says Chrome 133).",
		"**Resumption (layer 2).** `handshake=resumed` closes the client's connections between requests and keeps its session " +
			"cache; a request counts only if the server says it resumed (`x-tls-resumed`). net/http is given a TLS session cache, " +
			"as a caller who wants resumption sets one. azuretls keeps no session cache by default, so it never resumes (n/a). " +
			"mimicry over HTTP/3 resumes with 0-RTT, as Chrome does.",
		"**Connection pools.** net/http and tls-client get `MaxIdleConnsPerHost` 1024 (their default of 2 would close and reopen " +
			"connections at every concurrency above 2); the others keep their defaults.",
		"**The server is not the bottleneck.** Each server has its own CPU set (more cores than the client); its CPU use is " +
			"read from its cgroup over each window, shown in the tables, and a point where it passes 90% is discarded. Both " +
			"servers allow 1000 concurrent streams on HTTP/2 and HTTP/3, and nginx keeps connections for 10 million requests.",
		"**CPU and memory are per process.** Each load point, idle-memory measurement and page-load set runs in a worker process " +
			"of its own, so heaps, goroutines and GC never mix between clients. CPU per request is the process's user+system time " +
			"over the window divided by the requests completed in it; it includes the load generator's few goroutines, the same " +
			"for every client.",
		"**This machine.** A laptop: Docker runs in a VM, the CPU sets are the VM's CPUs (which of the host's performance and " +
			"efficiency cores serve them is up to macOS), and other load on the Mac shows up as noise. Short windows (see " +
			"Environment) trade precision for time; compare clients within a table rather than across runs.",
	}

	for _, n := range notes {
		w("- %s\n", n)
	}

	w("\n### Browser-faithful by design\n\n")
	w("Where mimicry is slower because it does what Chrome does, the tables mark it ‡:\n\n")
	w("- **HTTP/1.1, more than %d concurrent requests:** mimicry opens at most %d HTTP/1.1 connections per host (the profile's ", mimicryH1Limit, mimicryH1Limit)
	w("`connections.http1PerHost`, Chrome's limit) and queues the rest, first come first served; the other clients open one ")
	w("connection per concurrent request. Its requests/s and latency at 16, 64 and 256 measure the queue. `Config.MaxConnsPerHost` ")
	w("raises the limit, at the cost of looking unlike a browser (`mimicry-conns16` and `mimicry-conns64` when run).\n")
	w("- **Page loads over HTTP/1.1:** the same limit, per host: 31 requests over 3 hosts go out at most 6 at a time per host.\n")
	w("- **Page loads over HTTP/2:** mimicry coalesces www, static and api onto one connection (one certificate covers them and ")
	w("they resolve to one address), as Chrome does; the others open one per host. Fewer handshakes, all streams sharing one ")
	w("TCP congestion window: faster on a clean network, slower under loss. `Config.DisableCoalescing` opens one per host ")
	w("(`mimicry-nocoalescing` when run; decision 0037).\n")
	w("- **Page loads over HTTP/3, cold:** a new mimicry Transport knows nothing of HTTP/3: its first requests go over HTTP/2, ")
	w("the server's Alt-Svc starts a QUIC connection beside it, and later requests move to HTTP/3 once it is up (Chrome waits up ")
	w("to 300 ms for a QUIC attempt before going on TCP). The others are configured to force HTTP/3 from the first request, ")
	w("which no browser does for a site it has not seen advertise it. The protocol mix column shows it.\n")
	w("- **Page loads over HTTP/3, returning (`mimicry (returning)`):** a returning browser: new Transports sharing one ")
	w("`Config.AltSvc` cache that an earlier visit (one page load on a Transport of its own, not measured) filled, as a ")
	w("restarted Chrome starts with the Alt-Svc it saved. Each origin's first request races a fresh QUIC connection against TCP ")
	w("(TCP 300 ms later if QUIC is not up yet), as Chrome's does for an alternative it knows; no session tickets carry over, ")
	w("so no 0-RTT.\n")
	w("- **Idle memory over HTTP/3:** mimicry's idle state is a QUIC connection plus the HTTP/2 connection it learnt Alt-Svc on, ")
	w("which Chrome keeps open too.\n\n")
}

