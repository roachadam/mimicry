func (r *report) loadTables(w writer) {
	if len(r.Load) == 0 {
		return
	}

	w("## Layer 3: throughput and latency\n\n")
	w("GET /bytes/{size} on one warm client at each concurrency. Latency in ms. CPU: the client process's CPU time per request ")
	w("(µs) and cores used. B and allocs: allocated per request. GC: collections and total pause in the window. Heap: the ")
	w("client's peak heap (MB). Srv: the server's CPU use. ‡: browser-faithful by design.\n\n")

	type group struct {
		server string
		proto  target.Proto
		op     string
	}

	var groups []group

	for _, lp := range r.Load {
		g := group{
			server: lp.Server,
			proto:  lp.Proto,
			op:     lp.Op,
		}
		if !slices.Contains(groups, g) {
			groups = append(groups, g)
		}
	}

	for _, g := range groups {
		w("### %s, %s, %s\n\n", g.server, g.proto.Wire(), strings.TrimPrefix(g.op, "bytes-"))
		w("| client | conc | req/s | MB/s | p50 | p95 | p99 | CPU µs/req | cores | B/req | allocs/req | GC | GC pause ms | heap MB | goroutines | srv |\n")
		w("|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|\n")

		for _, lp := range r.Load {
			if lp.Server != g.server || lp.Proto != g.proto || lp.Op != g.op {
				continue
			}

			mark := ""
			if lp.Client == "mimicry" && lp.Proto == target.H1 && lp.Conc > mimicryH1Limit {
				mark = " ‡"
			}

			if !lp.valid() {
				w("| %s | %d | %s |||||||||||||||\n", lp.Client, lp.Conc, oneLine(lp.summary()))

				continue
			}

			res := lp.Result
			w("| %s%s | %d | %.0f | %.1f | %s | %s | %s | %.1f | %.2f | %s | %.0f | %d | %.1f | %.1f | %d | %s |\n",
				lp.Client, mark, lp.Conc, res.RPS, res.MBps, num(res.P50), num(res.P95), num(res.P99),
				res.CPUPerRequest, res.ClientCores, bytesNum(res.BytesPerRequest), res.AllocsPerRequest,
				res.GCs, res.GCPauseMs, res.HeapPeakMB, res.Goroutines, pct(res.ServerCPU))
		}

		w("\n")
	}
}

func (r *report) idleTable(w writer) {
	if len(r.Idle) == 0 {
		return
	}

	w("## Layer 4: memory per idle connection\n\n")
	w("%d clients built, then each warmed onto the protocol with GET /json and left idle; the heap (after GC) and goroutines ", r.Settings.IdleN)
	w("they hold, per client before any request and per idle connection after, and the goroutines' stacks in use per idle ")
	w("connection (`StackInuse`, which the heap leaves out). After close: what is left once every client ")
	w("is closed and dropped (heap KB in all, goroutines). GC under load is in the layer 3 tables.\n\n")
	w("| client | proto | heap KB/client | goroutines/client | heap KB/idle conn | goroutines/idle conn | stack KB/idle conn | after close: heap KB | after close: goroutines |\n")
	w("|---|---|---:|---:|---:|---:|---:|---:|---:|\n")

	for _, p := range target.Protos {
		for _, ip := range r.Idle {
			if ip.Proto != p {
				continue
			}

			if ip.Result == nil || ip.NA != "" || ip.Error != "" || ip.Result.Discarded != "" {
				why := ip.NA + ip.Error
				if ip.Result != nil {
					why += ip.Result.Discarded
				}

				w("| %s | %s | %s ||||||||\n", ip.Client, p, oneLine(why))

				continue
			}

			mark := ""
			if ip.Client == "mimicry" && p == target.H3 {
				mark = " ‡"
			}

			res := ip.Result
			w("| %s%s | %s | %.1f | %.1f | %.1f | %.1f | %.1f | %.0f | %d |\n", ip.Client, mark, p,
				res.HeapPerClientKB, res.GoroutinesPerClient, res.HeapPerConnKB, res.GoroutinesPerConn,
				res.StackPerConnKB, res.HeapAfterCloseKB, res.GoroutinesAfterClose)
		}
	}

	w("\n")
}

type pageSummary struct {
	medianMs float64
	p90Ms    float64
	conns    string
	protos   string
	errors   int
}

func pageStats(loads []scenario.PageLoad) pageSummary {
	var (
		times = make([]float64, 0, len(loads))
		conns []float64
		s     pageSummary
	)

	protos := map[target.Proto]int{}

	for _, l := range loads {
		s.errors += l.Errors

		times = append(times, l.Ms)

		if l.Conns >= 0 {
			conns = append(conns, float64(l.Conns))
		}

		for p, n := range l.Protos {
			protos[p] += n
		}
	}

	s.medianMs = quantile(times, 0.5)
	s.p90Ms = quantile(times, 0.9)

	s.conns = "?"
	if len(conns) > 0 {
		s.conns = strconv.FormatFloat(quantile(conns, 0.5), 'f', -1, 64)
	}

	var mix []string

	for _, p := range target.Protos {
		if n := protos[p]; n > 0 {
			mix = append(mix, fmt.Sprintf("%s %d", p, n))
		}
	}

	if len(loads) > 0 {
		s.protos = strings.Join(mix, ", ") + fmt.Sprintf(" (of %d)", len(loads)*(1+len(site.Subresources())))
	}

	return s
}

func quantile(v []float64, q float64) float64 {
	if len(v) == 0 {
		return 0
	}

	s := slices.Clone(v)
	sort.Float64s(s)

	return s[int(math.Round(q*float64(len(s)-1)))]
}

func (r *report) pageTables(w writer) {
	if len(r.Pages) == 0 {
		return
	}

	w("## Layer 5: page loads under network conditions\n\n")
	w("One HTML document from www, then its 30 subresources (www 10, static 14, api 6; about 1.5 MB) all requested at once, ")
	w("each client's pooling deciding how they go out, against the Go server (which counts the connections each load opens). ")
	w("Cold: a new client. Warm: the same client again. Times are the median (and 90th percentile) of %d loads, in ms; ", r.Settings.Reps)
	w("conns the median connections the server accepted meanwhile (TCP and QUIC); protocols the responses per protocol over all ")
	w("cold loads, then all warm ones. ")
	w("netem: %s. Through the proxies only HTTP/1.1 and HTTP/2 run: an HTTP proxy carries no UDP, and mimicry, as Chrome, ", r.Env.Netem)
	w("never uses HTTP/3 through a proxy by default (layer 6 measures HTTP/3 through SOCKS5).\n\n")

	conds := []string{}

	for _, pp := range r.Pages {
		if !slices.Contains(conds, pp.Condition) {
			conds = append(conds, pp.Condition)
		}
	}

	for _, proxy := range append([]target.ProxyKind{""}, target.ProxyKinds...) {
		for _, cond := range conds {
			var rows []pagePoint

			for _, pp := range r.Pages {
				if pp.Condition == cond && pp.Proxy == proxy {
					rows = append(rows, pp)
				}
			}

			if len(rows) == 0 {
				continue
			}

			title := conditionTitle(cond)
			if proxy != "" {
				title = fmt.Sprintf("through the proxy (%s), %s; the proxy adds %s", proxy, title, r.Env.ProxyDelay)
			}

			w("### Page load, %s\n\n", title)
			w("| client | proto | cold ms (p90) | cold conns | warm ms (p90) | warm conns | protocols cold | protocols warm | errors |\n")
			w("|---|---|---:|---:|---:|---:|---|---|---:|\n")

			for _, pp := range rows {
				if pp.Result == nil || pp.NA != "" || pp.Error != "" {
					w("| %s | %s | %s |||||||\n", pp.Client, pp.Proto, oneLine(pp.NA+pp.Error))

					continue
				}

				mark := ""
				if pp.Client == "mimicry" || pp.Client == "mimicry (returning)" {
					mark = " ‡"
				}

				cold := pageStats(pp.Result.Cold)
				warm := pageStats(pp.Result.Warm)
				w("| %s%s | %s | %.0f (%.0f) | %s | %.0f (%.0f) | %s | %s | %s | %d |\n", pp.Client, mark, pp.Proto,
					cold.medianMs, cold.p90Ms, cold.conns, warm.medianMs, warm.p90Ms, warm.conns, cold.protos, warm.protos,
					cold.errors+warm.errors)
			}

			w("\n")
		}
	}
}

func conditionTitle(name string) string {
	for _, c := range conditions {
		if c.Name == name {
			return c.String()
		}
	}

	return name
}

// skipped lists every n/a and discarded measurement with its reason.
func (r *report) skipped(w writer) {
	w("## n/a and discarded\n\n")

	var lines []string

	for _, lp := range r.Load {
		if !lp.valid() {
			lines = append(lines, fmt.Sprintf("load %s %s %s c=%d, %s: %s", lp.Server, lp.Proto, lp.Op, lp.Conc, lp.Client, oneLine(lp.summary())))
		}
	}

	for _, ip := range r.Idle {
		why := ip.NA + ip.Error
		if ip.Result != nil {
			why += ip.Result.Discarded
		}

		if why != "" {
			lines = append(lines, fmt.Sprintf("idle %s %s, %s: %s", ip.Server, ip.Proto, ip.Client, oneLine(why)))
		}
	}

	for _, pp := range r.Pages {
		if why := pp.NA + pp.Error; why != "" {
			lines = append(lines, fmt.Sprintf("page %s %s %s, %s: %s", pp.Condition, pp.Proto, pp.Proxy, pp.Client, oneLine(why)))
		}
	}

	for _, mp := range r.Multi {
		if !mp.valid() {
			lines = append(lines, fmt.Sprintf("multi %s via %s %s %s, %s: %s", mp.Proto, mp.Proxy, mp.Op, mp.rotationName(), mp.Client, oneLine(mp.summary())))
		}
	}

	if len(lines) == 0 {
		w("None in layers 3 to 6.\n\n")
	}

	for _, l := range lines {
		w("- %s\n", l)
	}

	w("\nLayers 1 and 2 print theirs as skipped benchmarks in the raw output.\n")
}

func oneLine(s string) string {
	s = strings.ReplaceAll(s, "\n", " ")
	s = strings.ReplaceAll(s, "|", "/")

	if len(s) > 220 {
		s = s[:220] + "…"
	}

	return s
}

func num(v float64) string {
	switch {
	case v >= 100:
		return strconv.FormatFloat(v, 'f', 0, 64)
	case v >= 10:
		return strconv.FormatFloat(v, 'f', 1, 64)
	}

	return strconv.FormatFloat(v, 'f', 2, 64)
}

func bytesNum(v float64) string {
	switch {
	case v >= 1<<20:
		return strconv.FormatFloat(v/(1<<20), 'f', 1, 64) + "M"
	case v >= 1<<10:
		return strconv.FormatFloat(v/(1<<10), 'f', 1, 64) + "K"
	}

	return strconv.FormatFloat(v, 'f', 0, 64)
}

func pct(v float64) string {
	if v < 0 {
		return "?"
	}

	return strconv.FormatFloat(100*v, 'f', 0, 64) + "%"
}
