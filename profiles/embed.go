// Package profiles holds the built-in browser profiles, one embedded JSON
// file per browser version and platform, taken from captures of the real
// browser. Each is checked once, on first use, and every accessor returns
// that one read-only profile.Profile: calling one costs nothing, and a
// client built from it copies nothing. Edit a copy with Profile.With.
// An accessor named for a browser and platform, such as ChromeMacOS or
// SafariIOS, tracks that browser's newest version on that platform
// (decision 0047); versioned accessors (Chrome156MacOS) stay fixed. Names
// carry the browser's version, not the operating system's: where the OS
// builds the connection (Safari, Chrome and Firefox on iOS), a profile matches the OS
// version it was captured on, which profiles/EVIDENCE.md records. Linux
// profiles (ChromeLinux, FirefoxLinux) are Google's and Mozilla's own
// builds, the same on every distribution, not a distribution's build
// (decision 0058). The accessors are generated by cmd/profilegen (go
// generate ./profiles).
package profiles

import (
	"embed"
	"fmt"
	"slices"
	"sync"

	"github.com/roachadam/mimicry/profile"
)

//go:generate go run ../cmd/profilegen

//go:embed data/*.json
var data embed.FS

// parsed holds each built-in profile, parsed and checked on first use.
var parsed = func() map[string]func() (profile.Profile, error) {
	m := make(map[string]func() (profile.Profile, error), len(names))
	for _, name := range names {
		m[name] = sync.OnceValues(func() (profile.Profile, error) {
			b, err := data.ReadFile("data/" + name + ".json")
			if err != nil {
				return profile.Profile{}, err
			}

			return profile.Parse(b)
		})
	}

	return m
}()

// load returns an embedded profile. Every embedded file is validated by the
// generator and by this package's tests, so a failure here is a build
// defect.
func load(name string) profile.Profile {
	p, err := ByName(name)
	if err != nil {
		panic(err)
	}

	return p
}

// ByName returns the built-in profile called name, for example
// "chrome-155-macos".
func ByName(name string) (profile.Profile, error) {
	get, ok := parsed[name]
	if !ok {
		return profile.Profile{}, fmt.Errorf("profiles: %q is not a built-in profile", name)
	}

	return get()
}

// Names lists every built-in profile, deprecated ones included.
func Names() []string {
	return slices.Clone(names)
}

// Supported lists the built-in profiles that are not deprecated: the newest
// five versions of each browser on each platform (decision 0035).
func Supported() []string {
	return slices.Clone(supported)
}
