// Command profilegen generates profiles/profiles.gen.go from
// profiles/data/*.json: accessors per profile and per browser's newest
// version on each platform (Chrome on macOS, ChromeWindows on Windows;
// decision 0047), and the name lists. It refuses invalid or misnamed files
// and sets that break the version policy (decision 0035).
//
// Run it with go generate ./profiles.
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"maps"
	"os"
	"path/filepath"
	"slices"
	"strconv"
	"strings"

	"github.com/roachadam/mimicry/profile"
)

// supportedVersions is how many of a browser's newest versions per platform
// are supported; older ones are deprecated (decision 0035).
const supportedVersions = 5

func main() {
	dir := "."
	if len(os.Args) > 1 {
		dir = os.Args[1]
	}

	src, err := generate(dir)
	if err != nil {
		fmt.Fprintln(os.Stderr, "profilegen:", err)
		os.Exit(1)
	}

	if err := os.WriteFile(filepath.Join(dir, "profiles.gen.go"), src, 0o600); err != nil { //nolint:gosec // a dev tool writing into the directory it was given
		fmt.Fprintln(os.Stderr, "profilegen:", err)
		os.Exit(1)
	}
}

// generate returns the source of profiles.gen.go for the profiles in
// dir/data.
func generate(dir string) ([]byte, error) {
	files, err := filepath.Glob(filepath.Join(dir, "data", "*.json"))
	if err != nil {
		return nil, err
	}

	if len(files) == 0 {
		return nil, fmt.Errorf("no profiles in %s", filepath.Join(dir, "data"))
	}

	slices.Sort(files)

	var profiles []*profile.Profile
	for _, f := range files {
		name := strings.TrimSuffix(filepath.Base(f), ".json")

		data, err := os.ReadFile(f) //nolint:gosec // files found by globbing the directory it was given
		if err != nil {
			return nil, err
		}

		p, err := profile.Parse(data)
		if err != nil {
			return nil, fmt.Errorf("%s: %w", f, err)
		}

		if p.Name != name {
			return nil, fmt.Errorf("%s: profile is named %q; the file must be %s.json", f, p.Name, p.Name)
		}

		if _, err := parseVersion(p.Version); err != nil {
			return nil, fmt.Errorf("%s: %w", f, err)
		}

		major, _, _ := strings.Cut(p.Version, ".")
		if want := p.Browser + "-" + major + "-" + p.Platform; p.Name != want {
			return nil, fmt.Errorf("%s: profile %s is %s %s on %s; it must be named %s", f, p.Name, p.Browser, p.Version, p.Platform, want)
		}

		profiles = append(profiles, p)
	}

	if err := checkPolicy(profiles); err != nil {
		return nil, err
	}

	var b bytes.Buffer
	b.WriteString("// Code generated by cmd/profilegen from data/*.json; DO NOT EDIT.\n\n")
	b.WriteString("package profiles\n\n")
	b.WriteString("import \"github.com/roachadam/mimicry/profile\"\n\n")

	latest := newest(profiles)
	for _, f := range slices.SortedFunc(maps.Keys(latest), compareFamilies) {
		p := latest[f]
		if f.platform == defaultPlatform {
			fmt.Fprintf(&b, "// %s returns a fresh copy of the newest %s profile, now %s (%s %s on %s).\n",
				f.accessor(), f.browser, p.Name, p.Browser, p.Version, p.Platform)
		} else {
			fmt.Fprintf(&b, "// %s returns a fresh copy of the newest %s profile on %s, now %s (%s %s on %s).\n",
				f.accessor(), f.browser, f.platform, p.Name, p.Browser, p.Version, p.Platform)
		}

		b.WriteString("// It moves to each new version as that version is added; use a\n")
		b.WriteString("// versioned accessor where a version must stay fixed.\n")
		fmt.Fprintf(&b, "func %s() *profile.Profile {\n\treturn load(%q)\n}\n\n", f.accessor(), p.Name)
	}

	for _, p := range profiles {
		fmt.Fprintf(&b, "// %s returns a fresh copy of the %s profile (%s %s on %s).\n",
			funcName(p.Name), p.Name, p.Browser, p.Version, p.Platform)

		if p.Deprecated {
			fmt.Fprintf(&b, "//\n// Deprecated: %s %s is older than the newest %d versions of %s on %s;\n// it is no longer refreshed. Use %s.\n",
				p.Browser, p.Version, supportedVersions, p.Browser, p.Platform, familyOf(p).accessor())
		}

		fmt.Fprintf(&b, "func %s() *profile.Profile {\n\treturn load(%q)\n}\n\n", funcName(p.Name), p.Name)
	}

	b.WriteString("var names = []string{\n")

	for _, p := range profiles {
		fmt.Fprintf(&b, "\t%q,\n", p.Name)
	}

	b.WriteString("}\n\n")
	b.WriteString("var supported = []string{\n")

	for _, p := range profiles {
		if !p.Deprecated {
			fmt.Fprintf(&b, "\t%q,\n", p.Name)
		}
	}

	b.WriteString("}\n")

	return format.Source(b.Bytes())
}

// checkPolicy refuses profiles that break decision 0035: per browser and
// platform, the newest supportedVersions versions are not deprecated and
// every older one is; each inherited scenario names an older built-in
// profile that holds its own captures of it.
func checkPolicy(profiles []*profile.Profile) error {
	byName := make(map[string]*profile.Profile, len(profiles))
	families := make(map[string][]*profile.Profile)

	for _, p := range profiles {
		byName[p.Name] = p

		key := p.Browser + " on " + p.Platform

		families[key] = append(families[key], p)
	}

	for _, key := range slices.Sorted(maps.Keys(families)) {
		family := families[key]
		slices.SortFunc(family, func(a, b *profile.Profile) int {
			return compareVersions(b.Version, a.Version)
		})

		for i, p := range family {
			if i > 0 && compareVersions(p.Version, family[i-1].Version) == 0 {
				return fmt.Errorf("%s and %s are both %s %s", family[i-1].Name, p.Name, key, p.Version)
			}

			switch {
			case i < supportedVersions && p.Deprecated:
				return fmt.Errorf("%s is deprecated but among the newest %d versions of %s", p.Name, supportedVersions, key)
			case i >= supportedVersions && !p.Deprecated:
				return fmt.Errorf("%s must be deprecated: it is older than the newest %d versions of %s", p.Name, supportedVersions, key)
			}
		}
	}

	for _, p := range profiles {
		for _, sc := range slices.Sorted(maps.Keys(p.CapturesFrom)) {
			from, ok := byName[p.CapturesFrom[sc]]
			switch {
			case !ok:
				return fmt.Errorf("%s: capturesFrom.%s: %q is not a built-in profile", p.Name, sc, p.CapturesFrom[sc])
			case from.Browser != p.Browser || from.Platform != p.Platform:
				return fmt.Errorf("%s: capturesFrom.%s: %s is not %s on %s", p.Name, sc, from.Name, p.Browser, p.Platform)
			case compareVersions(from.Version, p.Version) >= 0:
				return fmt.Errorf("%s: capturesFrom.%s: %s is not an older version", p.Name, sc, from.Name)
			case from.CapturesFrom[sc] != "":
				return fmt.Errorf("%s: capturesFrom.%s: %s inherits that scenario itself; name %s, which holds the captures", p.Name, sc, from.Name, from.CapturesFrom[sc])
			}
		}
	}

	return nil
}

// defaultPlatform is the platform whose newest profiles the unqualified
// accessors (Chrome) return. Other platforms' newest profiles have their
// own accessors (ChromeWindows); see decision 0047.
const defaultPlatform = "macos"

// family is one browser on one platform: the unit of the version policy
// and of a newest-version accessor.
type family struct {
	browser, platform string
}

func familyOf(p *profile.Profile) family {
	return family{browser: p.Browser, platform: p.Platform}
}

// accessor names the family's newest-version accessor: "Chrome" on the
// default platform, "ChromeWindows" on Windows.
func (f family) accessor() string {
	if f.platform == defaultPlatform {
		return browserFunc(f.browser)
	}

	return browserFunc(f.browser) + platformFunc(f.platform)
}

// compareFamilies orders families by browser, the default platform first.
func compareFamilies(a, b family) int {
	if c := strings.Compare(a.browser, b.browser); c != 0 {
		return c
	}

	if (a.platform == defaultPlatform) != (b.platform == defaultPlatform) {
		if a.platform == defaultPlatform {
			return -1
		}

		return 1
	}

	return strings.Compare(a.platform, b.platform)
}

// newest returns each family's newest profile. checkPolicy has refused two
// profiles of one version in a family, so there is no tie.
func newest(profiles []*profile.Profile) map[family]*profile.Profile {
	latest := make(map[family]*profile.Profile)
	for _, p := range profiles {
		f := familyOf(p)
		if cur, ok := latest[f]; !ok || compareVersions(p.Version, cur.Version) > 0 {
			latest[f] = p
		}
	}

	return latest
}

// parseVersion splits a version ("155", "26.1") into its numbers.
func parseVersion(v string) ([]int, error) {
	var out []int
	for part := range strings.SplitSeq(v, ".") {
		n, err := strconv.Atoi(part)
		if err != nil || n < 0 {
			return nil, fmt.Errorf("version %q must be numbers joined by dots", v)
		}

		out = append(out, n)
	}

	return out, nil
}

// compareVersions orders two versions parseVersion accepts, number by
// number.
func compareVersions(a, b string) int {
	va, _ := parseVersion(a)
	vb, _ := parseVersion(b)

	return slices.Compare(va, vb)
}

// browserFunc names a browser's newest-version accessor: "chrome" → "Chrome".
func browserFunc(browser string) string {
	return strings.ToUpper(browser[:1]) + browser[1:]
}

// platforms spells platform names the way Go identifiers usually do.
var platforms = map[string]string{
	"macos":    "MacOS",
	"ios":      "IOS",
	"chromeos": "ChromeOS",
	"windows":  "Windows",
}

// platformFunc spells a platform for an accessor's name: "macos" →
// "MacOS", "windows" → "Windows".
func platformFunc(platform string) string {
	if p, ok := platforms[platform]; ok {
		return p
	}

	return strings.ToUpper(platform[:1]) + platform[1:]
}

// funcName turns "chrome-155-macos" into "Chrome155MacOS". The name is a
// valid profile's (profile.Validate): lowercase letters and digits in
// non-empty parts joined by dashes.
func funcName(name string) string {
	var b strings.Builder
	for part := range strings.SplitSeq(name, "-") {
		b.WriteString(platformFunc(part))
	}

	return b.String()
}
